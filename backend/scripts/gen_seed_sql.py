"""Write supabase/seed.sql from backend/app/seed.py (the single source of seed data).

Usage (from the project root):  uv run python backend/scripts/gen_seed_sql.py
Re-running is safe: inserts use ON CONFLICT (id) DO NOTHING.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from pydantic import BaseModel

PROJECT_ROOT = Path(__file__).resolve().parents[2]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))  # allow running as a plain script

from backend.app.seed import seed_quotes, seed_requisition  # noqa: E402

SEED_SQL_PATH = PROJECT_ROOT / "supabase" / "seed.sql"
SKIP_COLUMNS = {"created_at", "updated_at"}  # database defaults fill these


def sql_literal(value: Any) -> str:
    """A Python value (already JSON-safe) as a SQL literal."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, (list, dict)):
        return sql_literal(json.dumps(value, ensure_ascii=False)) + "::jsonb"
    return "'" + str(value).replace("'", "''") + "'"  # standard SQL escaping of quotes


def insert_sql(table: str, rows: list[BaseModel]) -> str:
    records = [row.model_dump(mode="json", exclude=SKIP_COLUMNS) for row in rows]
    columns = list(records[0])
    values = ",\n".join("  (" + ", ".join(sql_literal(r[c]) for c in columns) + ")" for r in records)
    column_list = ", ".join(f'"{c}"' for c in columns)
    return f"insert into public.{table} ({column_list}) values\n{values}\non conflict (id) do nothing;\n"


def build_seed_sql() -> str:
    header = (
        "-- Generated by backend/scripts/gen_seed_sql.py from backend/app/seed.py. Do not edit by hand.\n"
        "-- Seed: PR-USP-1147 (Yeast Extract Powder) and Quotes A-D. Run after schema.sql.\n\n"
    )
    return header + insert_sql("requisitions", [seed_requisition()]) + "\n" + insert_sql("quotes", seed_quotes())


def main() -> None:
    SEED_SQL_PATH.parent.mkdir(parents=True, exist_ok=True)
    SEED_SQL_PATH.write_text(build_seed_sql(), encoding="utf-8", newline="\n")
    print(f"Wrote {SEED_SQL_PATH.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
